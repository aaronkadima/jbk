const DICTS: Record<Lang, Dict> = { pt, fr, en };
export type Key = keyof Dict;

export function translate(lang: Lang, key: Key | string, vars?: Record<string, string | number>): string {
  let s = (DICTS[lang] as Record<string, string>)[key] ?? (pt as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, typeof v === 'number' ? v.toLocaleString(lang) : v);
  return s;
}

export const errorText = (lang: Lang, code: string) =>
  translate(lang, `e_${code}` in pt ? `e_${code}` : 'e_generic');

export const money = (lang: Lang, value: number, currency: string) =>
  new Intl.NumberFormat(lang === 'pt' ? 'pt-BR' : lang === 'fr' ? 'fr-CD' : 'en-US', {
    style: 'currency', currency, maximumFractionDigits: currency === 'CDF' ? 0 : 2,
  }).format(value);

export const guessLang = (): Lang => {
  const l = (navigator.language || 'en').slice(0, 2);
  return l === 'pt' || l === 'fr' ? l : 'en';
};
